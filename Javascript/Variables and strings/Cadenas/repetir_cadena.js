let word = "Hello!";
let repeatedWord = word.repeat(3);
console.log(repeatedWord);  // "Hello!Hello!Hello!"

let wordDos = "Test";
console.log(wordDos.repeat(2.5));  // "TestTest"

console.log(wordDos.repeat(0));  // ""

let count = 4;
let repeatedWordDos = wordDos.repeat(count);
console.log(repeatedWordDos); // TestTestTestTest